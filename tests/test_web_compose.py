"""FR 2's generator half: ``rheo web compose`` renders the composed module file.

Seams under test: ``web_compose.render()`` (manifests in, generated TypeScript out,
pinned by a golden string over fixture manifests that exercise every generated shape —
navigation with default and narrowed roles, routes, a record view, a form, a search
provider, a module with no contribution, and a surface name that is not the module
id); ``installed_manifests()`` reading discovered entry points rather than the
``modules.installed`` allowlist; and the ``rheo web compose`` command's
``package.json`` check, driven through ``rheo_app_cli.main.main`` the way an operator
reaches it.

The fixture ids are ``_probe``-suffixed for the reason ``tests/harness/modules.py``
gives. The golden output is written out in full rather than rebuilt from the fixture,
so a dropped record view, form or search provider is a diff against text a person
wrote, not against a second copy of the renderer.
"""

